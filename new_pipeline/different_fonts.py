import json
from letter_analysis import *
from pathlib import Path
from funcs import *

output = Path.cwd() / "new_pipeline" / "outputs"
fdata = {}
lans = ["french", "german", "hun", "fin"]
stats = ["std_lower", "std_upper", "med_lower", "med_upper"]
fonts = ["arial", "cf", "cormorant", "tnr"]
struct = np.zeros((4,2,4,4)) # font, mode, language, statistic
for k,font in enumerate(fonts):
    with open(output / f"results_{font}.json", "r") as f:
        d = json.load(f)
    for i,lan in enumerate(lans):
        for j,stat in enumerate(stats):
            struct[k,0,i,j] = d[lan]["analytical"][stat]
            struct[k,1,i,j] = d[lan]["graphical"][stat]

mean = np.mean(struct, axis=2) # (font,mode,statistic)
std = np.std(struct, axis=2)
for lan in range(4):
    for font in range(4):
        for stat in range(4):
            for mode in range(2):
                struct[font,mode,lan,stat] = (struct[font,mode,lan,stat] - mean[font,mode,stat]) / std[font,mode,stat]

for i,font in enumerate(fonts):
    analytical = np.zeros((4,4)) # 16 = num lans * num stats
    graphical = np.zeros((4,4)) # 16 = num lans * num stats
    print('FONT:', font)
    for lan in range(4):
        for stat in range(4):
            analytical[stat,lan] = struct[i,0,lan,stat]
            graphical[stat,lan] = struct[i,1,lan,stat]
    print("ANALYTICAL")
    print(analytical)
    print('GRAPHICAL')
    print(graphical)
    print()

print('------------')
print('average differences:')
n = 4
c = 0
diffs = np.zeros((n,n))
for i in range(n):
    for j in range(i+1,n):
        c += 1
        a = struct[i,1,:,:]
        b = struct[j,1,:,:]
        diff = abs(a-b)
        diffs += diff

diffs /= c
print(diffs)

